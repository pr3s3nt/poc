import { fireEvent, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { ResourceDefinitionsPage } from './ResourceDefinitionsPage';
import { renderDefinition, backend, card, completeDefinition, field, submitDefinition } from '../../test/definitionKit';
import { sessionExpiredEvent } from '../../shared/api/client';

const criteriaTab = () => screen.getByRole('tab', { name: /Điều kiện áp dụng/ });
const configurationTab = () => screen.getByRole('tab', { name: 'Cấu hình' });
afterEach(() => vi.unstubAllGlobals());

describe('Resource Definition v3 task layout', () => {
  it('starts collapsed, supports keyboard tabs and preserves invalid/unrepresentable JSON, mapping, typed values and provision through tab/mode changes', async () => {
    const user = userEvent.setup();
    const { posted } = backend();
    renderDefinition(<ResourceDefinitionsPage />);
    await waitFor(() => expect(screen.getByRole('option', { name: 'vpc' })).toBeEnabled());
    await user.selectOptions(field('Loại tài nguyên'), 'k8s-namespace');
    expect(screen.getAllByRole('tab')).toHaveLength(2);
    expect(screen.getByText('Thiết lập nâng cao · ánh xạ & tài nguyên liên quan').closest('details')).not.toHaveAttribute('open');
    await completeDefinition(user, { id: 'ns-v3', type: 'k8s-namespace' });
    await user.click(screen.getByRole('button', { name: '+ Thêm tài nguyên đi kèm' }));
    await user.type(field('Descriptor tài nguyên đi kèm 1'), 'redis.audit#shared.cache');
    fireEvent.change(field('Params tài nguyên đi kèm 1 (JSON object)'), { target: { value: '{"number":2,"nested":{"enabled":false},"ref":"${context.env.id}"}' } });
    await user.click(field('Tài nguyên đi kèm 1: redis chờ k8s-namespace tạo xong (is_dependent)'));
    await user.click(field('Tài nguyên đi kèm 1: các tài nguyên đang dùng k8s-namespace cũng phải chờ redis (match_dependents)'));
    await user.click(screen.getByRole('button', { name: 'Nâng cao: JSON nâng cao' }));
    const provision = JSON.parse((field('Quy tắc tạo tài nguyên liên quan (JSON object)') as HTMLTextAreaElement).value);
    await user.click(screen.getByRole('button', { name: 'Nâng cao: biểu mẫu' }));
    await user.click(screen.getByRole('button', { name: 'Nâng cao: JSON nâng cao' }));
    const original = (field('Ánh xạ module JSON') as HTMLTextAreaElement).value;
    fireEvent.change(field('Ánh xạ module JSON'), { target: { value: '{bad json' } });
    await user.click(screen.getByRole('button', { name: 'Cấu hình tài nguyên' }));
    expect(screen.getByRole('heading', { name: 'Cấu hình đã đăng ký' })).toBeVisible();
    expect(screen.queryByRole('tab')).not.toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'Tạo cấu hình' }));
    expect(field('Ánh xạ module JSON')).toHaveValue('{bad json');
    expect(field('ID cấu hình (Definition ID)')).toHaveValue('ns-v3');

    await user.click(criteriaTab());
    expect(configurationTab()).toHaveAttribute('aria-selected', 'false');
    for (const text of ['Sao chép từ cấu hình khác', 'Kiểm tra cấu hình được chọn', 'Cách hệ thống chọn cấu hình']) expect(screen.getByText(text).closest('details')).not.toHaveAttribute('open');
    expect(screen.getByRole('group', { name: 'Ngữ cảnh kiểm tra matching' })).not.toBeVisible();
    criteriaTab().focus();
    await user.keyboard('{ArrowLeft}');
    expect(configurationTab()).toHaveFocus();
    expect(configurationTab()).toHaveAttribute('aria-selected', 'true');
    expect(field('Ánh xạ module JSON')).toHaveValue('{bad json');
    await user.click(screen.getByRole('button', { name: 'Nâng cao: biểu mẫu' }));
    expect(field('Ánh xạ module JSON')).toHaveValue('{bad json');
    expect(JSON.parse((field('Quy tắc tạo tài nguyên liên quan (JSON object)') as HTMLTextAreaElement).value)).toEqual(provision);
    fireEvent.change(field('Ánh xạ module JSON'), { target: { value: '{"unsupported":{},"provider_bindings":{}}' } });
    await user.click(screen.getByRole('button', { name: 'Nâng cao: biểu mẫu' }));
    expect(field('Ánh xạ module JSON')).toHaveValue('{"unsupported":{},"provider_bindings":{}}');
    fireEvent.change(field('Ánh xạ module JSON'), { target: { value: original } });
    fireEvent.change(field('Quy tắc tạo tài nguyên liên quan (JSON object)'), { target: { value: '{bad provision' } });
    await user.click(screen.getByRole('button', { name: 'Nâng cao: biểu mẫu' }));
    expect(field('Ánh xạ module JSON')).toHaveValue(original);
    expect(field('Quy tắc tạo tài nguyên liên quan (JSON object)')).toHaveValue('{bad provision');
    expect(screen.getByRole('button', { name: 'Nâng cao: JSON nâng cao' })).toHaveAttribute('aria-pressed', 'true');
    fireEvent.change(field('Quy tắc tạo tài nguyên liên quan (JSON object)'), { target: { value: JSON.stringify(provision) } });
    await user.click(screen.getByRole('button', { name: 'Nâng cao: biểu mẫu' }));
    expect(field('Output module cung cấp name')).toHaveValue('name');
    expect(card('name')).toHaveTextContent('Namespace của môi trường');
    expect(field('Tài nguyên đi kèm 1: redis chờ k8s-namespace tạo xong (is_dependent)')).toBeChecked();
    await user.click(screen.getByText('Xem bản đang nhập trước khi lưu'));
    const reviewed = JSON.parse(screen.getByLabelText('Bản cấu hình đang nhập').textContent ?? '');
    expect(reviewed.provision).toEqual(provision);
    await submitDefinition(user);
    await waitFor(() => expect(posted).toHaveLength(1));
    expect(posted[0]).toEqual(reviewed);
  });

  it('keeps selected empty conditions across tabs and copy cancellation, and copies all five fields and wildcard cases independently', async () => {
    const user = userEvent.setup();
    const source = [{ env_type: 'staging', app_id: 'shop', env_id: 'production', res_id: 'db', class: ' custom ' }, {}];
    const { posted } = backend({ definitions: [{ key: 'source', resourceType: 'k8s-namespace', driverType: 'terraform', criteria: source }] });
    renderDefinition(<ResourceDefinitionsPage />);
    await waitFor(() => expect(screen.getByRole('option', { name: 'vpc' })).toBeEnabled());
    await completeDefinition(user, { id: 'ns-copy', type: 'k8s-namespace' });
    await user.click(criteriaTab());
    await user.click(screen.getByRole('button', { name: '+ Thêm điều kiện' }));
    await user.click(configurationTab());
    await submitDefinition(user);
    expect(criteriaTab()).toHaveAttribute('aria-selected', 'true');
    expect(screen.getByRole('alert')).toHaveTextContent('Nhập giá trị');
    await user.click(screen.getByText('Sao chép từ cấu hình khác'));
    await user.selectOptions(field('Sao chép điều kiện từ cấu hình khác'), 'source');
    await user.click(screen.getByRole('button', { name: 'Sao chép điều kiện' }));
    await user.click(screen.getByRole('button', { name: 'Giữ điều kiện hiện tại' }));
    expect(field('Điều kiện 1 Loại môi trường')).toHaveValue('');
    expect(posted).toHaveLength(0);
    await user.click(screen.getByRole('button', { name: 'Sao chép điều kiện' }));
    await user.click(screen.getByRole('button', { name: 'Thay bằng bản sao chép' }));
    expect(field('Điều kiện 1 Class')).toHaveValue(' custom ');
    expect(within(screen.getByRole('region', { name: 'Trường hợp 2' })).getByText(/wildcard/)).toBeInTheDocument();
    expect(within(screen.getByRole('region', { name: 'Trường hợp 1' })).getByRole('button', { name: '+ Thêm điều kiện' })).toBeDisabled();
    await submitDefinition(user);
    await waitFor(() => expect(posted).toHaveLength(1));
    expect(posted[0]?.criteria).toEqual(source);
  });

  it('invalidates a hidden pending/result matching response when the draft or session changes', async () => {
    const user = userEvent.setup();
    backend();
    const original = globalThis.fetch;
    let release: (response: Response) => void = () => undefined;
    vi.stubGlobal('fetch', vi.fn((input: string | URL | Request, init?: RequestInit) => String(input).endsWith('/matching-preview')
      ? new Promise<Response>((resolve) => { release = resolve; }) : original(input, init)));
    renderDefinition(<ResourceDefinitionsPage />);
    await waitFor(() => expect(screen.getByRole('option', { name: 'vpc' })).toBeEnabled());
    await completeDefinition(user, { id: 'ns-matching', type: 'k8s-namespace' });
    await user.click(criteriaTab());
    await user.click(screen.getByText('Kiểm tra cấu hình được chọn'));
    await user.selectOptions(field('Ứng dụng kiểm tra'), 'shop');
    await user.selectOptions(field('Môi trường kiểm tra'), 'staging');
    await user.type(field('ID tài nguyên kiểm tra (res_id)'), 'ns');
    await user.type(field('Class kiểm tra'), 'default');
    const result = { status: 'NO_MATCH', candidates: [], snapshot: { marker: 'only-original', environmentVersion: 1 } };
    await user.click(screen.getByRole('button', { name: 'Kiểm tra matching' }));
    await user.click(screen.getByText('Kiểm tra cấu hình được chọn'));
    await user.click(configurationTab());
    await user.type(field('Tên hiển thị'), ' changed');
    release(Response.json(result));
    await user.click(criteriaTab());
    await user.click(screen.getByText('Kiểm tra cấu hình được chọn'));
    expect(screen.queryByRole('region', { name: 'Kết quả matching chính xác' })).not.toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'Kiểm tra matching' }));
    release(Response.json(result));
    await screen.findByRole('region', { name: 'Kết quả matching chính xác' });
    await user.click(configurationTab());
    fireEvent(window, new Event(sessionExpiredEvent));
    await user.click(criteriaTab());
    expect(screen.queryByRole('region', { name: 'Kết quả matching chính xác' })).not.toBeInTheDocument();
  });
});
