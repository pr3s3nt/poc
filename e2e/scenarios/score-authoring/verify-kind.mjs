import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
const evidence = resolve(process.env.ORCH_EVIDENCE_DIR ?? '');
assert(process.env.ORCH_EVIDENCE_DIR && !evidence.startsWith(resolve('.') + '/'));
const receipt = JSON.parse(readFileSync(join(evidence, 'receipt.json'), 'utf8'));
assert(receipt.deployed, 'Require successful product deployment');
const kubeconfig = process.env.ORCH_SCORE_KUBECONFIG, context = process.env.ORCH_SCORE_CONTEXT;
assert(kubeconfig && context, 'Explicit kubeconfig/context required');
const args = ['--kubeconfig', kubeconfig, '--context', context];
const run = more => execFileSync('kubectl', [...args, ...more], { encoding: 'utf8', timeout: 30_000, stdio: ['ignore', 'pipe', 'pipe'] });
const get = more => JSON.parse(run([...more, '-o', 'json']));
const ns = receipt.namespaceAccess.namespace;
const namespace = get(['get', 'namespace', ns]);
assert.equal(namespace.metadata.uid, receipt.namespaceAccess.namespaceUid);
assert.equal(namespace.metadata.labels['orchestrator-managed'], 'true');
const deployment = get(['-n', ns, 'get', 'deployment', 'database-client']);
assert.equal(deployment.status.availableReplicas, 1);
const env = deployment.spec.template.spec.containers.find(x => x.name === 'main').env;
assert.equal(env.find(x => x.name === 'ACCEPTANCE_REVISION').value, 'second');
assert(env.find(x => x.name === 'PGHOST').value.endsWith('.' + ns + '.svc'));
const logs = run(['-n', ns, 'logs', 'deployment/database-client', '--tail=20']);
assert(logs.includes('score83-database-ready'));
const statefulsets = get(['-n', ns, 'get', 'statefulsets']).items;
assert.equal(statefulsets.length, 1);
assert.equal(statefulsets[0].status.readyReplicas, 1);
const databasePod = get(['-n', ns, 'get', 'pods']).items.find(x => x.metadata.ownerReferences?.some(o => o.uid === statefulsets[0].metadata.uid));
assert(databasePod);
const sql = run(['-n', ns, 'exec', databasePod.metadata.name, '--', 'sh', '-c', 'PGPASSWORD="$POSTGRES_PASSWORD" psql -h 127.0.0.1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Atc "SELECT 1"']);
assert.equal(sql.trim(), '1');
const cron = get(['-n', ns, 'get', 'cronjob', 'scheduled-report']);
assert.equal(cron.spec.schedule, '* * * * *');
assert.equal(cron.spec.timeZone, 'Asia/Bangkok');
assert.equal(cron.spec.suspend, false);
let completed;
const deadline = Date.now() + 120_000;
while (Date.now() < deadline) {
 completed = get(['-n', ns, 'get', 'jobs']).items.find(x => x.metadata.ownerReferences?.some(o => o.uid === cron.metadata.uid) && x.status.succeeded > 0 && x.spec.template.spec.containers.some(c => c.args?.some(a => a.includes('score83-scheduled-report-second'))));
 if (completed) break;
 await new Promise(resolve => setTimeout(resolve, 3000));
}
assert(completed, 'No completed invocation of the updated real CronJob');
const identities = [deployment, cron, statefulsets[0], ...get(['-n', ns, 'get', 'persistentvolumeclaims']).items].map(x => ({ kind: x.kind, name: x.metadata.name, uid: x.metadata.uid }));
const previousFile = process.env.ORCH_SCORE_BEFORE_IDENTITIES;
if (previousFile) for (const before of JSON.parse(readFileSync(previousFile, 'utf8'))) assert(identities.some(x => x.kind === before.kind && x.name === before.name && x.uid === before.uid), 'Update replaced a resource identity');
writeFileSync(join(evidence, 'runtime-verification.json'), JSON.stringify({ namespace: ns, namespaceUid: namespace.metadata.uid, identities, updatedJob: { name: completed.metadata.name, uid: completed.metadata.uid }, checks: ['Deployment available', 'resolved PostgreSQL binding', 'application database readiness', 'real SQL query', 'CronJob schedule/timezone', 'updated scheduled execution', 'resource UID preservation'] }, null, 2), { mode: 0o600 });
console.log('PASS: real Deployment/PostgreSQL/CronJob, updated execution and preserved infrastructure identities');
